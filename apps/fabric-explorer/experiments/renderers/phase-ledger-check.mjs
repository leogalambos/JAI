/** Controlled phase-overlap regression; attribution never erases a genuine cold-start failure. */
import assert from 'node:assert/strict';
import { createPhaseLedger } from './src/phase-ledger.ts';
let now = 10; const ledger = createPhaseLedger(() => now);
ledger.mark('cold-bootstrap'); now = 100; ledger.mark('empty-renderer'); now = 500; ledger.mark('graph-build'); now = 1000; ledger.mark('animation'); now = 1100;
ledger.record([{ startTime: 20, duration: 942 }, { startTime: 1010, duration: 51 }, { startTime: 990, duration: 30 }]);
const result = ledger.snapshot();
assert.equal(result.overallMaxTaskMs, 942); assert.equal(result.noObservedTaskOver200ms, false);
assert.deepEqual(result.tasks[0].overlaps.map(item => item.phase), ['cold-bootstrap', 'empty-renderer', 'graph-build']);
assert.deepEqual(result.tasks[2].overlaps.map(item => item.phase), ['graph-build', 'animation']);
assert.equal(result.tasks.length, 3); assert.equal(result.tasks[0].duration, 942);
assert.equal(result.phaseSummaries.find(phase => phase.name === 'animation').maxWholeTaskMs, 51);
let occurrenceTime = 0;
const repeated = createPhaseLedger(() => occurrenceTime);
repeated.mark('graph-build'); occurrenceTime = 100; repeated.mark('idle');
occurrenceTime = 200; repeated.mark('graph-build'); occurrenceTime = 300;
repeated.record([{ startTime: 10, duration: 51 }]);
const separated = repeated.snapshot();
assert.equal(separated.phaseSummaries[0].taskCount, 1);
assert.equal(separated.phaseSummaries[2].taskCount, 0, 'A repeated name cannot inherit tasks from an earlier occurrence');
assert.equal(separated.phaseSummaries[2].maxWholeTaskMs, null);
assert.deepEqual(separated.tasks[0].overlaps.map(item => item.phaseIndex), [0]);
assert.equal(separated.overallMaxTaskMs, 51);
repeated.record([{ startTime: 90, duration: 120 }]);
const spanning = repeated.snapshot();
assert.deepEqual(spanning.tasks[1].overlaps.map(item => item.phaseIndex), [0, 1, 2]);
assert.equal(spanning.phaseSummaries[0].taskCount, 2);
assert.equal(spanning.phaseSummaries[2].taskCount, 1);
assert.equal(spanning.phaseSummaries[2].maxWholeTaskMs, 120, 'Keep the whole task duration when it crosses a boundary');
assert.equal(spanning.tasks[1].duration, 120);
console.log('PASS: raw startup failure retained, overlaps preserved, repeated phase occurrences independently attributed.');
